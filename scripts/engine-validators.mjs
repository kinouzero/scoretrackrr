import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { format, resolveConfig } from 'prettier';
import {
  rulesSchema,
  configSchema,
  commandSchema,
  eventSchema,
  stateSchema,
} from '../src/lib/domain/engine/schemas.ts';

const schemas = {
  validateRules: rulesSchema,
  validateConfig: configSchema,
  validateCommand: commandSchema,
  validateEvent: eventSchema,
  validateState: stateSchema,
};
const ajv = new Ajv({
  strict: true,
  allErrors: false,
  ownProperties: true,
  code: { source: true, esm: true, lines: true },
});
for (const schema of Object.values(schemas)) ajv.addSchema(schema);
const code = standaloneCode(
  ajv,
  Object.fromEntries(Object.entries(schemas).map(([key, schema]) => [key, schema.$id])),
);
// Keep generated validators self-contained: no runtime compiler, eval or helpers.
if (/\brequire\s*\(|\beval\s*\(|\bnew\s+Function\b|\bimport\s/.test(code))
  throw new Error('Generated validators require an unexpected runtime dependency');
const destination = fileURLToPath(
  new URL('../src/lib/domain/engine/validators.generated.js', import.meta.url),
);
const output = await format(
  `// @ts-nocheck\n// Generated by pnpm generate:engine. Do not edit manually.\n${code}`,
  { ...(await resolveConfig(destination)), filepath: destination },
);
if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')) !== output)
    throw new Error('Engine validators are stale. Run pnpm generate:engine.');
  console.log('Engine validators match the trusted schemas.');
} else {
  await writeFile(destination, output);
  console.log('Generated static engine validators.');
}
