// Typed message bindings. Translatable text lives only in locales/*.json.
import type { MessageValues, Translator } from './catalog';
function localizeTree<T extends object>(tree: T, translate: Translator): T {
  const cache = new Map<PropertyKey, unknown>();
  return new Proxy(tree, {
    get(target, key, receiver) {
      const value = Reflect.get(target, key, receiver);
      if (typeof value === 'string') return translate(value);
      if (value && typeof value === 'object') {
        if (!cache.has(key)) cache.set(key, localizeTree(value, translate));
        return cache.get(key);
      }
      return value;
    },
  });
}
